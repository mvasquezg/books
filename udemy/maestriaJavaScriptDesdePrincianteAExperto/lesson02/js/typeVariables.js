//Tipo de dato String
var namePerson = "Miguel Angel";
console.log("Tipo de datos cadena: " + namePerson);

//Tipo de dato Number
var agePerson = 30;
console.log("Tipo de datos númerico: " + agePerson);

//Tipo de dato Boolean
var isActive = true;
console.log("Tipo de datos booleano: " + isActive);

//Tipo de dato Undefined
var lastName;
console.log("Tipo de datos indefinido: " + lastName);

//Tipo de dato Null
var address = null;
console.log("Tipo de datos nulo: " + address);

var objectPerson = {
    name: "Miguel Angel",
    lastName: "Gonzalez",
    age: 30,
    isActive: true
};

console.log("Tipo de datos objeto: " + objectPerson);